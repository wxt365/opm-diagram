import { writeFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

test.use({ baseURL: 'http://127.0.0.1:5178' });
test('真实子图生成、审查失败保留预览、重新审查后自动保存', async ({ page }, info) => {
  test.skip(process.env.OPM_SCOPED_REVIEW_E2E !== 'true', '需隔离后端及 assistant-scoped-review 驱动');
  test.setTimeout(360_000); const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.goto('/projects'); await page.getByTestId('p01-create-project').click();
  await page.getByTestId('ov01-project-name').fill(`子图审查隔离回归-${Date.now()}`);
  await page.getByRole('button', { name: '创建并继续', exact: true }).click();
  await page.getByTestId('p02-create-model').click(); await page.getByTestId('ov02-model-name').fill('咖啡烘焙审查');
  await page.getByRole('button', { name: '创建并打开工作台', exact: true }).click();
  await expect(page.getByTestId('hs-save')).toBeEnabled();
  const root = (await page.getByTestId('opd-navigator').locator('[aria-current="page"]').getAttribute('data-testid'))!;
  await page.getByTestId('p03-tool-process').click();
  const processNode = page.locator('.x6-node').filter({ hasText: 'Process 1' });
  await expect(processNode).toBeVisible(); await processNode.click({ position: { x: 30, y: 16 } });
  await page.getByTestId(root.replace('p03-context-', 'opd-add-')).click();
  await page.getByTestId('opd-refinement-name').fill('烘焙细化子图'); await page.getByTestId('opd-refine').click();
  await expect(page.getByTestId('opd-navigator').locator('[aria-current="page"]')).toContainText('烘焙细化子图');
  const contextId = (await page.getByTestId('opd-navigator').locator('[aria-current="page"]').getAttribute('data-testid'))!.replace('p03-context-', '');
  const pathname = new URL(page.url()).pathname, projectId = pathname.split('/projects/')[1]!.split('/')[0]!, modelId = pathname.split('/models/')[1]!.split('/')[0]!;
  const scope = { projectId, modelId, contextId }, session = await page.evaluate(() => window.__OPM_LOCAL_SESSION__);
  const headers = { Origin: 'http://127.0.0.1:5178', 'X-OPM-Session': session! };
  const open = async () => (await (await page.request.post(`/api/v2/projects/${projectId}/models/${modelId}/draft/open`, { headers, data: { request_id: `request.test.${Date.now()}`, context_id: contextId } })).json()).draft_token;
  const list = async () => (await (await page.request.post('/api/assistant/list', { headers, data: scope })).json())[0];
  const before = await open(); await page.getByTestId('left-tab-assistant').click(); const panel = page.locator('[data-testid="assistant-panel"]:visible');
  const started = Date.now();
  await panel.getByTestId('assistant-input').fill('在当前子图细化咖啡豆烘焙。只创建咖啡豆对象、它的生豆和熟豆两个状态、烘焙过程，以及生豆经烘焙变成熟豆的输入输出指定 Effect 关系。咖啡豆前后是同一对象，不要增加消耗和产出关系，也不要增加其他设备或物料。不修改父图。合理布局并生成完整方案。');
  await panel.getByTestId('assistant-send').click(); await expect(panel.getByTestId('assistant-running')).toBeVisible();
  await expect(panel.getByTestId('assistant-running')).toHaveCount(0, { timeout: 200_000 });
  const blocked = await list(), original = blocked.proposals.at(-1);
  expect(original.status).toBe('blocked'); expect(blocked.run.code).toBe('REVIEW_RETRIES_EXHAUSTED');
  expect(await open()).toEqual(before); await expect(page.getByTestId('assistant-canvas-preview')).toBeVisible();
  await expect(page.locator('.x6-node').filter({ hasText: '咖啡豆' }).first()).toBeVisible();
  await expect(panel.getByTestId('assistant-apply')).toHaveCount(0); await expect(panel.getByTestId('assistant-review-retry')).toBeEnabled();
  await page.screenshot({ path: info.outputPath('review-blocked-preview.png') });
  const retryStarted = Date.now(); await panel.getByTestId('assistant-review-retry').click();
  await expect(panel.getByTestId('assistant-running')).toBeVisible();
  await expect(panel.getByTestId('assistant-running')).toHaveCount(0, { timeout: 150_000 });
  await expect(panel.getByTestId('assistant-apply')).toHaveCount(0);
  const done = await list(), proposal = done.proposals.at(-1);
  expect(proposal.id).toBe(original.id); expect(proposal.commandId).toBe(original.commandId);
  expect(proposal.review.review_scope.current_context_id).toBe(contextId);
  expect(proposal.review.review_scope.related_context_ids).toContain(root.replace('p03-context-', ''));
  expect(proposal.review.issues.filter((issue: { severity: string }) => issue.severity === 'ERROR')).toEqual([]);
  expect(proposal.validation.validation_summary.blocking).toBe(0); expect(proposal.status).toBe('applied');
  await panel.getByTestId('assistant-proposals').locator(':scope > summary').click();
  await expect(panel.getByTestId('assistant-review-scope')).toContainText('本图完整审查');
  await page.screenshot({ path: info.outputPath('review-recovered-preview.png') });
  await writeFile(info.outputPath('review-proof.json'), JSON.stringify({ scope, generationAndFailureMs: retryStarted - started, retryMs: Date.now() - retryStarted,
    before, command: proposal.command, validation: proposal.validation, review: proposal.review }, null, 2));
  const after = await open(); expect(after.edit_seq).toBe(before.edit_seq + 1);
  // 应用请求完成后工作台还会重新读取投影，等新草稿进入页面再保存。
  await expect(page.getByTestId('hs-draft-identity')).toContainText(`编辑 ${after.edit_seq}`);
  await expect(page.getByTestId('assistant-canvas-preview')).toHaveCount(0);
  await expect(page.getByTestId('hs-save')).toBeEnabled();
  await page.getByTestId('hs-save').click(); await expect(page.getByTestId('hs-save-state')).toHaveText('已手动保存', { timeout: 30_000 });
  await page.reload(); await expect(page.getByTestId('hs-save')).toBeEnabled(); await page.getByTestId('left-tab-assistant').click();
  await expect(panel.getByTestId('assistant-proposal')).toContainText('已保存'); expect(await open()).toEqual(after); expect(errors).toEqual([]);
});
